"""Reporter agent: writes the incident report (Markdown).

The structured sections (timeline, evidence, debate, actions) are rendered
deterministically from case data, so the report is always factually tied to
the evidence. The LLM - if available - contributes the executive summary and
impact narrative only.
"""

from __future__ import annotations

from sentinelcrew.agents.base import Agent
from sentinelcrew.models import Verdict
from sentinelcrew.orchestration.state import CaseState

SUMMARY_SCHEMA = {
    "type": "object",
    "required": ["executive_summary", "impact", "recommendations"],
    "properties": {
        "executive_summary": {"type": "string", "maxLength": 1500},
        "impact": {"type": "string", "maxLength": 800},
        "recommendations": {"type": "array", "items": {"type": "string"}, "maxItems": 6},
    },
}

VERDICT_LABEL = {
    Verdict.TRUE_POSITIVE: "TRUE POSITIVE - confirmed incident",
    Verdict.NEEDS_REVIEW: "NEEDS REVIEW - inconclusive",
    Verdict.FALSE_POSITIVE: "FALSE POSITIVE - benign activity",
    Verdict.NOISE: "NOISE - auto-closed at triage",
}


def _md_escape(text: str) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ")


def default_summary(state: CaseState) -> dict[str, object]:
    assessment = state.assessment
    verdict = assessment.verdict if assessment else Verdict.NOISE
    alert = state.alert
    if verdict == Verdict.NOISE:
        summary = f"Alert '{alert.rule_name}' scored below the noise threshold and was closed automatically."
        impact = "None."
    elif verdict == Verdict.FALSE_POSITIVE:
        upheld = [c.evidence for r in state.debate for c in r.challenges if c.status.value == "upheld"]
        summary = (
            f"Alert '{alert.rule_name}' was investigated and closed as a false positive. "
            + (f"Benign explanation confirmed: {upheld[0]}." if upheld else "")
        )
        impact = "No business impact; no containment required."
    else:
        hypothesis = state.investigation.hypothesis if state.investigation else ""
        summary = f"{hypothesis} Confidence after adversarial review: {assessment.confidence:.0%}."  # type: ignore[union-attr]
        hosts = {e.host for e in (state.investigation.timeline if state.investigation else []) if e.host}
        impact = f"Potentially affected assets: {', '.join(sorted(hosts)) or 'unknown'}."
    recommendations = []
    if any(a.status.value == "pending_approval" for a in state.actions):
        recommendations.append("Review and approve the pending high-risk containment actions.")
    if verdict == Verdict.TRUE_POSITIVE:
        recommendations += [
            "Hunt for the same indicators across the estate.",
            "Rotate credentials of any affected accounts.",
        ]
    return {"executive_summary": summary, "impact": impact, "recommendations": recommendations}


def render_report(state: CaseState, summary: dict[str, object], provider: str) -> str:
    a = state.alert
    assessment = state.assessment
    verdict = assessment.verdict if assessment else Verdict.NOISE
    lines = [
        f"# Incident Report - {state.case_id}",
        "",
        f"**Alert:** {a.rule_name} &nbsp;|&nbsp; **Source:** {a.source} &nbsp;|&nbsp; "
        f"**Time:** {a.timestamp:%Y-%m-%d %H:%M:%S} UTC",
        "",
        f"**Verdict:** {VERDICT_LABEL[verdict]}  ",
        f"**Confidence:** {assessment.confidence:.0%}  " if assessment else "**Confidence:** n/a  ",
        f"**Priority:** {state.triage.priority.value.upper() if state.triage else 'n/a'}  ",
        f"**Generated by:** SentinelCrew agents (reasoning engine: {provider})",
        "",
        "## 1. Executive summary",
        "",
        str(summary["executive_summary"]),
        "",
        "## 2. Impact",
        "",
        str(summary["impact"]),
        "",
        "## 3. Entities",
        "",
        "| Field | Value |",
        "|---|---|",
    ]
    lines += [f"| {k} | `{_md_escape(v)}` |" for k, v in a.entities().items()]
    if state.triage:
        t = state.triage
        lines += [
            "",
            "## 4. Triage",
            "",
            f"Hybrid score **{t.score:.2f}** = 0.4 x ML anomaly ({t.anomaly_score:.2f}) + 0.6 x rules ({t.rule_score:.2f}). "
            f"Category: **{t.category}**.",
            "",
        ]
        lines += [f"- {_md_escape(r)}" for r in t.reasons]
    if state.investigation:
        inv = state.investigation
        lines += ["", "## 5. Evidence", "", "| Weight | Technique | Finding | Detail |", "|---|---|---|---|"]
        lines += [
            f"| {f.weight:.2f} | {f.technique_id or '-'} | {_md_escape(f.title)} | {_md_escape(f.detail)} |"
            for f in inv.findings
        ] or ["| - | - | No findings | - |"]
        lines += ["", "### Timeline (first 30 events)", "", "```"]
        lines += [e.short() for e in inv.timeline[:30]] or ["(no events)"]
        lines += ["```"]
    if state.intel and state.intel.results:
        lines += ["", "## 6. Threat intelligence", "", "| Indicator | Type | Reputation | Tags |", "|---|---|---|---|"]
        lines += [
            f"| `{r.indicator}` | {r.kind} | {r.reputation:.2f} | {', '.join(r.tags)} |"
            for r in state.intel.results[:15]
        ]
        if state.intel.techniques:
            lines += ["", "**MITRE ATT&CK:** " + ", ".join(f"{t['id']} {t['name']} ({t['tactic']})" for t in state.intel.techniques)]
    if state.similar_cases:
        lines += ["", "## 7. Similar past cases", ""]
        lines += [f"- **{c.case_id}** ({c.similarity:.0%}) - {c.title} -> {c.verdict}" for c in state.similar_cases]
    if state.debate:
        initial = state.initial_assessment.confidence if state.initial_assessment else 0.0
        lines += [
            "",
            "## 8. Adversarial review (Critic debate)",
            "",
            f"Initial confidence **{initial:.0%}** -> final **{assessment.confidence:.0%}** "  # type: ignore[union-attr]
            f"after {len(state.debate)} round(s).",
            "",
            "| Round | Challenge | Outcome | Evidence | Impact |",
            "|---|---|---|---|---|",
        ]
        for r in state.debate:
            for c in r.challenges:
                lines.append(
                    f"| {r.round} | {_md_escape(c.claim)} | {c.status.value} | {_md_escape(c.evidence)} | {c.impact:+.2f} |"
                )
    lines += ["", "## 9. Response actions", ""]
    if state.actions:
        lines += ["| Action | Target | Risk | Status | Result |", "|---|---|---|---|---|"]
        lines += [
            f"| {x.kind} | `{x.target}` | {x.risk.value} | {x.status.value} | {_md_escape(x.result or x.rationale)} |"
            for x in state.actions
        ]
    else:
        lines.append("No response actions were required.")
    recs = summary.get("recommendations") or []
    if recs:
        lines += ["", "## 10. Recommendations", ""]
        lines += [f"- {r}" for r in recs]  # type: ignore[union-attr]
    lines += ["", "---", "_All response actions are executed in a simulated environment._", ""]
    return "\n".join(lines)


class ReporterAgent(Agent):
    name = "Reporter"
    role = "Writes clear incident reports for analysts and management."

    def run(self, state: CaseState) -> None:
        summary = default_summary(state)
        verdict = state.assessment.verdict if state.assessment else Verdict.NOISE
        if verdict in (Verdict.TRUE_POSITIVE, Verdict.NEEDS_REVIEW):
            llm = self.ask_json(
                state,
                "Write an executive summary (3-5 sentences, for management), a one-paragraph impact "
                "statement and up to 5 concrete recommendations for this incident. Use only the facts given.",
                {
                    "alert": state.alert.rule_name,
                    "verdict": verdict.value,
                    "confidence": state.assessment.confidence if state.assessment else None,
                    "hypothesis": state.investigation.hypothesis if state.investigation else "",
                    "findings": [f.detail for f in (state.investigation.findings if state.investigation else [])],
                    "critic": [c.evidence for r in state.debate for c in r.challenges],
                    "actions": [f"{a.kind}({a.target}) -> {a.status.value}" for a in state.actions],
                },
                SUMMARY_SCHEMA,
            )
            if llm:
                summary = llm
        provider = self.llm.name if self.llm else "deterministic"
        state.report_markdown = render_report(state, summary, provider)
        self.say(state, "result", f"Incident report written ({len(state.report_markdown.splitlines())} lines).")
